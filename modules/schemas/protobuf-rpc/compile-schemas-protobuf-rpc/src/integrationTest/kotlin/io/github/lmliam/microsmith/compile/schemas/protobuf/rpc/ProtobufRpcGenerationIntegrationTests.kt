package io.github.lmliam.microsmith.compile.schemas.protobuf.rpc

import io.github.lmliam.microsmith.dsl.microsmith
import io.github.lmliam.microsmith.dsl.schemas.protobuf.protobuf
import io.github.lmliam.microsmith.dsl.schemas.protobuf.rpc.service
import io.github.lmliam.microsmith.dsl.schemas.schemas
import io.github.lmliam.microsmith.gen.generateTo
import io.kotest.core.spec.style.StringSpec
import io.kotest.engine.spec.tempdir
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldContain
import kotlin.io.path.exists
import kotlin.io.path.readText

class ProtobufRpcGenerationIntegrationTests :
    StringSpec(
        {
            "generateTo emits rpc services with imported request and response messages" {
                val model = microsmith {
                    schemas {
                        protobuf {
                            message("GetUserRequest")
                            message("GetUserResponse")
                            service("UserService") { "GetUser" { "GetUserRequest" to "GetUserResponse" } }
                        }
                    }
                }

                tempdir("protobuf-rpc-generation-").toPath().let { outputRoot ->
                    model.generateTo(outputRoot)
                    val generatedFile = outputRoot.resolve("proto/UserService.proto")
                    val contents = generatedFile.readText()

                    generatedFile.exists() shouldBe true
                    contents.shouldContain("// Generated by Microsmith")
                    contents.shouldContain("import \"GetUserRequest.proto\";")
                    contents.shouldContain("import \"GetUserResponse.proto\";")
                    contents.shouldContain("service UserService {")
                    contents.shouldContain("rpc GetUser (GetUserRequest) returns (GetUserResponse);")
                }
            }

            "generateTo emits qualified rpc services under the namespaced proto path" {
                val model = microsmith {
                    schemas {
                        protobuf {
                            "acme.user.v1" {
                                message("GetUserRequest")
                                message("GetUserResponse")
                                service("UserService") { "GetUser" { "GetUserRequest" to "GetUserResponse" } }
                            }
                        }
                    }
                }

                tempdir("protobuf-rpc-generation-").toPath().let { outputRoot ->
                    model.generateTo(outputRoot)
                    val generatedFile = outputRoot.resolve("proto/acme/user/v1/UserService.proto")
                    val contents = generatedFile.readText()

                    generatedFile.exists() shouldBe true
                    contents.shouldContain("// Generated by Microsmith")
                    contents.shouldContain("package acme.user.v1;")
                    contents.shouldContain("import \"acme/user/v1/GetUserRequest.proto\";")
                    contents.shouldContain("import \"acme/user/v1/GetUserResponse.proto\";")
                    contents.shouldContain(
                        "rpc GetUser (acme.user.v1.GetUserRequest) returns (acme.user.v1.GetUserResponse);",
                    )
                }
            }

            "generateTo emits a service without rpcs" {
                val model = microsmith { schemas { protobuf { service("EmptyService") {} } } }

                tempdir("protobuf-rpc-generation-").toPath().let { outputRoot ->
                    model.generateTo(outputRoot)
                    val contents = outputRoot.resolve("proto/EmptyService.proto").readText()

                    contents.shouldContain("service EmptyService {}")
                }
            }
        },
    )
