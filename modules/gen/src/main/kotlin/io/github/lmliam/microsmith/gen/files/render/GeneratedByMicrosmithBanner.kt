package io.github.lmliam.microsmith.gen.files.render

import java.nio.file.Path

internal object GeneratedByMicrosmithBanner {
    private const val HEADER_TEXT = "Generated by Microsmith"
    private val xmlExtensions = setOf("csproj", "fsproj", "props", "targets", "vbproj", "xml")
    private val slashCommentExtensions =
        setOf(
            "c",
            "cc",
            "cpp",
            "cs",
            "go",
            "gradle",
            "groovy",
            "h",
            "hpp",
            "java",
            "js",
            "jsx",
            "kt",
            "kts",
            "proto",
            "rs",
            "scala",
            "swift",
            "ts",
            "tsx",
        )
    private val hashCommentExtensions =
        setOf(
            "bash",
            "conf",
            "env",
            "properties",
            "py",
            "rb",
            "sh",
            "toml",
            "yaml",
            "yml",
            "zsh",
        )

    fun prepend(path: Path, contents: String): String {
        val comment = resolveComment(path) ?: return contents
        if (contents.startsWith(comment)) {
            return contents
        }
        if (comment.startsWith("#") && contents.startsWith("#!")) {
            val shebangEnd = contents.indexOf('\n')
            if (shebangEnd == -1) {
                return "$contents\n$comment\n"
            }
            val shebang = contents.substring(0, shebangEnd)
            val remainder = contents.substring(shebangEnd + 1)
            return listOf(shebang, comment, remainder).joinToString(separator = "\n")
        }
        return if (contents.isEmpty()) {
            "$comment\n"
        } else {
            "$comment\n$contents"
        }
    }

    private fun resolveComment(path: Path): String? {
        val fileName = path.fileName.toString()
        val extension = fileName.substringAfterLast('.', missingDelimiterValue = "")
        return when {
            extension in xmlExtensions -> "<!-- $HEADER_TEXT -->"
            extension in slashCommentExtensions -> "// $HEADER_TEXT"
            extension in hashCommentExtensions -> "# $HEADER_TEXT"
            else -> null
        }
    }
}
