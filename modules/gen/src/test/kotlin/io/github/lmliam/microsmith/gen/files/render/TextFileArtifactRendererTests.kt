package io.github.lmliam.microsmith.gen.files.render

import io.github.lmliam.microsmith.artifact.files.TextFileArtifact
import io.github.lmliam.microsmith.artifact.files.TextFileArtifactId
import io.kotest.core.spec.style.StringSpec
import io.kotest.matchers.shouldBe
import java.nio.charset.StandardCharsets
import java.nio.file.Path

class TextFileArtifactRendererTests :
    StringSpec({
        val renderer = TextFileArtifactRenderer()

        "render prepends generated banner for proto files" {
            val rendered =
                renderer.render(
                    TextFileArtifact(
                        id = TextFileArtifactId(relativePath = Path.of("proto", "User.proto")),
                        contents = "syntax = \"proto3\";",
                    ),
                )

            String(rendered.contents, StandardCharsets.UTF_8) shouldBe
                """
                // Generated by Microsmith
                syntax = "proto3";
                """.trimIndent()
        }

        "render prepends generated banner for xml-based project files" {
            val projectFile =
                Path.of(
                    "src",
                    "apps",
                    "UserService.Api",
                    "UserService.Api.csproj",
                )
            val rendered =
                renderer.render(
                    TextFileArtifact(
                        id = TextFileArtifactId(relativePath = projectFile),
                        contents = "<Project />",
                    ),
                )

            String(rendered.contents, StandardCharsets.UTF_8) shouldBe
                """
                <!-- Generated by Microsmith -->
                <Project />
                """.trimIndent()
        }

        "render prepends generated banner for xml-based props files" {
            val rendered =
                renderer.render(
                    TextFileArtifact(
                        id = TextFileArtifactId(relativePath = Path.of("Directory.Build.props")),
                        contents = "<Project />",
                    ),
                )

            String(rendered.contents, StandardCharsets.UTF_8) shouldBe
                """
                <!-- Generated by Microsmith -->
                <Project />
                """.trimIndent()
        }

        "render keeps the generated banner stable when origins are present" {
            val rendered =
                renderer.render(
                    TextFileArtifact(
                        id = TextFileArtifactId(relativePath = Path.of("proto", "User.proto")),
                        contents = "syntax = \"proto3\";",
                        origins = setOf("schemas.protobuf.pkg.User", "schemas.protobuf.pkg.UserCreated"),
                    ),
                )

            String(rendered.contents, StandardCharsets.UTF_8) shouldBe
                """
                // Generated by Microsmith
                syntax = "proto3";
                """.trimIndent()
        }

        "render keeps xml banners stable when origins are present" {
            val rendered =
                renderer.render(
                    TextFileArtifact(
                        id = TextFileArtifactId(relativePath = Path.of("Directory.Packages.props")),
                        contents = "<Project />",
                        origins = setOf("services.solutions.Platform.packages.Serilog.AspNetCore"),
                    ),
                )

            String(rendered.contents, StandardCharsets.UTF_8) shouldBe
                """
                <!-- Generated by Microsmith -->
                <Project />
                """.trimIndent()
        }

        "render leaves unsupported text formats unchanged" {
            val rendered =
                renderer.render(
                    TextFileArtifact(
                        id = TextFileArtifactId(relativePath = Path.of("notes.txt")),
                        contents = "plain text",
                    ),
                )

            String(rendered.contents, StandardCharsets.UTF_8) shouldBe "plain text"
        }

        "render does not duplicate an existing generated banner" {
            val rendered =
                renderer.render(
                    TextFileArtifact(
                        id = TextFileArtifactId(relativePath = Path.of("proto", "User.proto")),
                        contents = "// Generated by Microsmith\nsyntax = \"proto3\";",
                    ),
                )

            String(rendered.contents, StandardCharsets.UTF_8) shouldBe
                """
                // Generated by Microsmith
                syntax = "proto3";
                """.trimIndent()
        }
    })
