/**
 * Pure rendering helpers from validated protobuf models to deterministic `.proto` text.
 */
private const val INDENT = "  "
private const val GENERATED_BY_HEADER = "// Generated by Microsmith"
private const val PROTO3_SYNTAX_LINE = """syntax = "proto3";"""
private val PRIMITIVE_TYPE_RENDERINGS =
    mapOf(
        PrimitiveType.INT32 to "int32",
        PrimitiveType.INT64 to "int64",
        PrimitiveType.UINT32 to "uint32",
        PrimitiveType.UINT64 to "uint64",
        PrimitiveType.SINT32 to "sint32",
        PrimitiveType.SINT64 to "sint64",
        PrimitiveType.FIXED32 to "fixed32",
        PrimitiveType.FIXED64 to "fixed64",
        PrimitiveType.SFIXED32 to "sfixed32",
        PrimitiveType.SFIXED64 to "sfixed64",
        PrimitiveType.STRING to "string",
        PrimitiveType.BOOL to "bool",
        PrimitiveType.FLOAT to "float",
        PrimitiveType.DOUBLE to "double",
        PrimitiveType.BYTES to "bytes",
    )

internal fun renderProtobufFile(
    qualifiedName: QualifiedSchemaName,
    declaration: String,
    imports: List<String> = emptyList(),
): String = buildString {
    appendLine(GENERATED_BY_HEADER)
    appendLine(PROTO3_SYNTAX_LINE)
    qualifiedName.packageName?.let { appendLine("package $it;") }
    imports.sorted().forEach { appendLine("import \"$it\";") }
    appendLine(declaration)
}

internal fun Message.renderMessage(): String = buildString {
    appendLine("message $name {")
    reservedSection()?.let { appendIndentedLine(it) }
    fields.forEach { appendIndentedLine(it.renderField()) }
    oneofs.forEach { appendIndentedLine(it.renderOneof()) }
    append("}")
}

internal fun Enum.renderEnum(): String = buildString {
    appendLine("enum $name {")
    reservedSection()?.let { appendLine(it.prependIndent(INDENT)) }
    values.forEach { appendLine(it.renderEnumValue().prependIndent(INDENT)) }
    append("}")
}

private fun Field.renderField(): String = buildString {
    val field = this@renderField
    val prefix = (field as? CardinalityField)?.cardinality?.renderPrefix().orEmpty()
    append(prefix)
    when (field) {
        is ScalarField -> append("${field.primitive.renderValueType()} ${field.name} = ${field.index};")
        is ReferenceField -> append("${field.reference.name} ${field.name} = ${field.index};")
        is MapField -> append("${field.type.renderMapType()} ${field.name} = ${field.index};")
        is OneofField -> invalidTopLevelOneofField(field.name)
    }
}

private fun Oneof.renderOneof(): String = buildString {
    appendLine("oneof $name {")
    fields.forEach { appendLine(it.renderOneofField().prependIndent(INDENT)) }
    append("}")
}

private fun OneofField.renderOneofField(): String = "${fieldType.renderValueType()} $name = $index;"

private fun MapType.renderMapType(): String = "map<${key.renderValueType()}, ${value.renderValueType()}>"

private fun Cardinality.renderPrefix(): String = when (this) {
    Cardinality.REQUIRED -> ""
    Cardinality.OPTIONAL -> "optional "
    Cardinality.REPEATED -> "repeated "
}

private fun PrimitiveType.renderValueType(): String =
    PRIMITIVE_TYPE_RENDERINGS[this] ?: invariantViolation("Unsupported protobuf primitive type: $this")

private fun ValueType.renderValueType(): String = when (this) {
    is PrimitiveType -> renderValueType()
    is Reference -> name
}

private fun EnumValue.renderEnumValue(): String = "$name = $index;"

private fun Type.reservedSection(): String? {
    val entries =
        when (this) {
            is Message -> reserved
            is Enum -> reserved
        }
    if (entries.isEmpty()) {
        return null
    }

    val namesLine =
        entries
            .filterIsInstance<ReservedName>()
            .takeIf { it.isNotEmpty() }
            ?.joinToString(", ") { "\"${it.name}\"" }
            ?.let { "reserved $it;" }

    val indexesLine =
        entries
            .filterNot { it is ReservedName }
            .takeIf { it.isNotEmpty() }
            ?.joinToString(", ") { it.renderReservedIndex() }
            ?.let { "reserved $it;" }

    return listOfNotNull(namesLine, indexesLine).joinToString("\n")
}

private fun Reserved.renderReservedIndex(): String = when (this) {
    is ReservedIndex -> index.toString()
    is ReservedRange -> "${indexRange.first} to ${indexRange.last}"
    is ReservedToMax -> "$from to max"
    is ReservedName -> invariantViolation("Reserved names are rendered separately from reserved indexes.")
}

private fun StringBuilder.appendIndentedLine(value: String) {
    appendLine(value.prependIndent(INDENT))
}
